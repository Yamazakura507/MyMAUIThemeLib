namespace ThemeForge.Abstractions.Knowledge
{
    /// <summary>
    /// Известные именованные роли цветов внутри одного компонента.
    /// </summary>
    public static class KnownNamedColorRoles
    {
        /// <summary>
        /// Основной трек/дорожка, например для Slider/ProgressBar.
        /// </summary>
        public const string Track = "Track";

        /// <summary>
        /// Вторичная/максимальная часть трека.
        /// </summary>
        public const string MaximumTrack = "MaximumTrack";

        /// <summary>
        /// Ползунок/бегунок.
        /// </summary>
        public const string Thumb = "Thumb";

        /// <summary>
        /// Индикатор, например для Switch/CheckBox/RadioButton.
        /// </summary>
        public const string Indicator = "Indicator";

        /// <summary>
        /// Ripple/нажатие.
        /// </summary>
        public const string Ripple = "Ripple";

        /// <summary>
        /// Placeholder-текст.
        /// </summary>
        public const string Placeholder = "Placeholder";

        /// <summary>
        /// Иконка внутри компонента.
        /// </summary>
        public const string Icon = "Icon";

        /// <summary>
        /// Прогресс/заполнение.
        /// </summary>
        public const string Progress = "Progress";

        /// <summary>
        /// Текст компонента.
        /// </summary>
        public const string Text = "Text";

        /// <summary>
        /// Фон компонента.
        /// </summary>
        public const string Background = "Background";

        /// <summary>
        /// Граница компонента.
        /// </summary>
        public const string Border = "Border";
    }
}
